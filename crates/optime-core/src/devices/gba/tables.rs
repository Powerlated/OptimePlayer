/// `umul3232H32`: the high 32 bits of a 32×32-bit unsigned multiply.
#[inline]
pub fn umul3232h32(a: u32, b: u32) -> u32 {
    ((u64::from(a) * u64::from(b)) >> 32) as u32
}

/// `MidiKeyToFreq` from `pret/pokeemerald` `src/m4a.c`: the data rate (Hz) at which a
/// DirectSound wave with header frequency `wav_freq` (sample rate << 10) plays `key`,
/// fine-adjusted by `fine_adjust` (1/256ths of a semitone).
pub fn midi_key_to_freq(wav_freq: u32, key: u8, fine_adjust: u8) -> u32 {
    let (key, fine_adjust) = if key > 178 {
        (178u8, 255u8)
    } else {
        (key, fine_adjust)
    };
    let fine_adjust_shifted = u32::from(fine_adjust) << 24;

    let val1 = SCALE_TABLE[key as usize];
    let val1 = FREQ_TABLE[(val1 & 0xF) as usize] >> (val1 >> 4);

    let val2 = SCALE_TABLE[key as usize + 1];
    let val2 = FREQ_TABLE[(val2 & 0xF) as usize] >> (val2 >> 4);

    umul3232h32(
        wav_freq,
        val1.wrapping_add(umul3232h32(val2.wrapping_sub(val1), fine_adjust_shifted)),
    )
}

/// `MidiKeyToCgbFreq`: the GB frequency-register value for `key` on CGB channel `chan_num`
/// (1 = square 1, 2 = square 2, 3 = wave, 4 = noise → NR43 value).
pub fn midi_key_to_cgb_freq(chan_num: u8, key: u8, fine_adjust: u8) -> u32 {
    if chan_num == 4 {
        let key = key.saturating_sub(21).min(59);
        u32::from(NOISE_TABLE[key as usize])
    } else {
        let (key, fine_adjust) = if key <= 35 {
            (0u8, 0u8)
        } else if key - 36 > 130 {
            (130u8, 255u8)
        } else {
            (key - 36, fine_adjust)
        };

        let val1 = CGB_SCALE_TABLE[key as usize];
        let val1 = i32::from(CGB_FREQ_TABLE[(val1 & 0xF) as usize]) >> (val1 >> 4);

        let val2 = CGB_SCALE_TABLE[key as usize + 1];
        let val2 = i32::from(CGB_FREQ_TABLE[(val2 & 0xF) as usize]) >> (val2 >> 4);

        (val1 + ((i32::from(fine_adjust) * (val2 - val1)) >> 8) + 2048) as u32
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Direct transcription of the C `MidiKeyToFreq` used as the oracle.
    fn c_midi_key_to_freq(wav_freq: u32, mut key: u8, fine_adjust: u8) -> u32 {
        let mut fine_adjust_shifted = u32::from(fine_adjust) << 24;
        if key > 178 {
            key = 178;
            fine_adjust_shifted = 255 << 24;
        }
        let v1 = SCALE_TABLE[key as usize];
        let val1 = FREQ_TABLE[(v1 & 0xF) as usize] >> (v1 >> 4);
        let v2 = SCALE_TABLE[key as usize + 1];
        let val2 = FREQ_TABLE[(v2 & 0xF) as usize] >> (v2 >> 4);
        umul3232h32(
            wav_freq,
            val1.wrapping_add(umul3232h32(val2.wrapping_sub(val1), fine_adjust_shifted)),
        )
    }

    #[test]
    fn midi_key_to_freq_matches_pokeemerald() {
        // The common case: a 13379 Hz sample (freq field = rate << 10) plays at its recorded
        // rate at middle C (key 60).
        let wav_freq = 13379u32 << 10;
        assert_eq!(midi_key_to_freq(wav_freq, 60, 0), 13379);
        // One octave up doubles (within integer truncation).
        let up = midi_key_to_freq(wav_freq, 72, 0);
        assert!((i64::from(up) - 2 * 13379).abs() <= 1, "got {up}");

        for key in [0u8, 1, 35, 36, 60, 90, 127, 178, 200, 255] {
            for fine in [0u8, 1, 127, 255] {
                for freq in [8000u32 << 10, 13379 << 10, 31536 << 10] {
                    assert_eq!(
                        midi_key_to_freq(freq, key, fine),
                        c_midi_key_to_freq(freq, key, fine),
                        "key={key} fine={fine} freq={freq}"
                    );
                }
            }
        }
    }

    #[test]
    fn cgb_freq_register_hits_known_pitches() {
        // Key 36 (C2 ≈ 65.4 Hz): register 44 → 131072 / (2048 − 44) ≈ 65.4 Hz.
        let x = midi_key_to_cgb_freq(1, 36, 0);
        assert_eq!(x, 44);
        let hz = 131072.0 / (2048.0 - x as f64);
        assert!((hz - 65.4).abs() < 0.1, "got {hz}");
        // Noise channel returns NR43 values straight from the table.
        assert_eq!(midi_key_to_cgb_freq(4, 21, 0), 0xD7);
        assert_eq!(midi_key_to_cgb_freq(4, 76, 0), 0x04);
        assert_eq!(midi_key_to_cgb_freq(4, 255, 0), 0x00);
        // Below the table, keys clamp to entry 0.
        assert_eq!(midi_key_to_cgb_freq(4, 0, 0), 0xD7);
    }
}
